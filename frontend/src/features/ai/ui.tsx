const REASON_COPY: Record<AiUnavailableReason, string> = {
  missing_key: "AI is not configured. This is a template result.",
  timeout: "The AI provider timed out. Showing a template result.",
  provider_error: "The AI provider returned an error. Showing a template result.",
  invalid_response: "The AI response was invalid. Showing a template result.",
  rate_limit: "The AI provider rate-limited this request. Showing a template result.",
};

export function AiSourceNote({ result }: { result: AiEnvelope }) {
  return (
    <div className="flex flex-wrap items-center gap-2">
      <Badge variant={result.source === "ai" ? "primary" : "outline"}>
        {result.source === "ai" ? "AI" : "Template"}
      </Badge>
      {result.unavailableReason ? (
        <p className="text-sm text-muted-foreground">
          {REASON_COPY[result.unavailableReason]}
        </p>
      ) : result.source === "heuristic" ? (
        <p className="text-sm text-muted-foreground">
          Template result — not AI-generated.
        </p>
      ) : (
        <p className="text-sm text-muted-foreground">Generated by the AI provider.</p>
      )}
    </div>
  );
}

export function SuggestedTaskList({
  tasks,
  projectId,
  canWrite,
}: {
  tasks: SuggestedTask[];
  projectId?: string;
  canWrite?: boolean;
}) {
  const createTask = useCreateTask();
  const [added, setAdded] = useState<string[]>([]);

  if (tasks.length === 0) {
    return <p className="text-sm text-muted-foreground">No suggested tasks.</p>;
  }

  return (
    <ul className="space-y-3">
      {tasks.map((task, index) => {
        const key = `${task.title}-${index}`;
        const already = added.includes(key);
        return (
          <li
            key={key}
            className="flex items-start justify-between gap-3 rounded-xl bg-secondary/70 px-3 py-2.5"
          >
            <div className="min-w-0">
              <p className="font-medium">{task.title}</p>
              {task.description ? (
                <p className="text-sm text-muted-foreground">{task.description}</p>
              ) : null}
              <p className="mt-1 text-xs text-muted-foreground">
                {task.priority}
                {task.estimatedHours != null ? ` · ${task.estimatedHours}h` : ""}
                {task.dueDate ? ` · due ${task.dueDate}` : ""}
              </p>
            </div>
            {canWrite ? (
              <Button
                type="button"
                size="sm"
                variant="outline"
                disabled={already || createTask.isPending}
                onClick={() => {
                  void createTask
                    .mutateAsync({
                      title: task.title,
                      description: task.description || undefined,
                      priority: task.priority,
                      estimatedHours: task.estimatedHours,
                      dueDate: task.dueDate
                        ? fromDateInputValue(task.dueDate)
                        : undefined,
                      projectId,
                    })
                    .then(() => setAdded((current) => [...current, key]));
                }}
              >
                {already ? "Added" : "Add task"}
              </Button>
            ) : null}
          </li>
        );
      })}
    </ul>
  );
}

export function AiPlanDialog({
  open,
  onOpenChange,
  projectId,
  canWrite,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  projectId?: string;
  canWrite?: boolean;
}) {
  const workspaceId = useWorkspaceStore((state) => state.currentWorkspaceId);
  const status = useAiStatus(open ? workspaceId : null);
  const plan = useGeneratePlan();
  const [prompt, setPrompt] = useState("");

  function handleOpenChange(next: boolean) {
    if (!next) {
      setPrompt("");
      plan.reset();
    }
    onOpenChange(next);
  }

  return (
    <CreateResourceDialog
      open={open}
      onOpenChange={handleOpenChange}
      title="Task plan"
      description={
        status.data?.enabled
          ? "Describe the outcome. The plan loads after you generate it."
          : "AI is optional. Without a provider key you still get a labeled template plan."
      }
    >
      <form
        className="space-y-4"
        onSubmit={(event: FormEvent) => {
          event.preventDefault();
          void plan.mutateAsync({ prompt, projectId });
        }}
      >
        <div className="space-y-2">
          <Label htmlFor="ai-plan-prompt">What needs planning?</Label>
          <textarea
            id="ai-plan-prompt"
            className={nativeTextareaClass}
            value={prompt}
            onChange={(event) => setPrompt(event.target.value)}
            placeholder="Launch the Q3 onboarding flow"
            autoFocus
            required
          />
        </div>
        <div className="flex justify-end">
          <Button type="submit" disabled={!prompt.trim() || plan.isPending}>
            {plan.isPending ? "Generating..." : "Generate plan"}
          </Button>
        </div>
        {plan.error ? (
          <p className="text-sm text-destructive">{plan.error.message}</p>
        ) : null}
        {plan.data ? (
          <div className="space-y-3">
            <AiSourceNote result={plan.data} />
            <div>
              <p className="font-medium">{plan.data.title}</p>
              <p className="text-sm text-muted-foreground">{plan.data.summary}</p>
            </div>
            <SuggestedTaskList
              tasks={plan.data.tasks}
              projectId={projectId}
              canWrite={canWrite}
            />
          </div>
        ) : null}
      </form>
    </CreateResourceDialog>
  );
}

export function AiAssistCard({
  taskId,
  projectId,
}: {
  taskId?: string;
  projectId?: string;
}) {
  const assist = useAiAssist();
  const [question, setQuestion] = useState("What should I do next?");

  return (
    <Surface>
      <h2 className="text-base font-semibold tracking-tight">AI assistance</h2>
      <p className="mt-1 text-sm text-muted-foreground">
        Optional. Core task editing does not wait on this.
      </p>
      <form
        className="mt-4 space-y-3"
        onSubmit={(event) => {
          event.preventDefault();
          void assist.mutateAsync({ question, taskId, projectId });
        }}
      >
        <Input
          value={question}
          onChange={(event) => setQuestion(event.target.value)}
          placeholder="Ask for the next action"
        />
        <Button type="submit" disabled={!question.trim() || assist.isPending}>
          {assist.isPending ? "Asking..." : "Ask"}
        </Button>
      </form>
      {assist.error ? (
        <p className="mt-3 text-sm text-destructive">{assist.error.message}</p>
      ) : null}
      {assist.data ? (
        <div className="mt-4 space-y-3">
          <AiSourceNote result={assist.data} />
          <p className="text-sm">{assist.data.answer}</p>
          {assist.data.suggestions.length > 0 ? (
            <ul className="list-disc space-y-1 pl-5 text-sm text-muted-foreground">
              {assist.data.suggestions.map((item) => (
                <li key={item}>{item}</li>
              ))}
            </ul>
          ) : null}
        </div>
      ) : null}
    </Surface>
  );
}

export function AiExtractCard({
  meetingId,
  projectId,
  defaultText,
  canWrite,
}: {
  meetingId?: string;
  projectId?: string;
  defaultText?: string;
  canWrite?: boolean;
}) {
  const extract = useExtractTasks();
  const [text, setText] = useState(defaultText ?? "");

  return (
    <Surface>
      <h2 className="text-base font-semibold tracking-tight">Extract tasks</h2>
      <p className="mt-1 text-sm text-muted-foreground">
        Pull suggested tasks from notes. Nothing is created until you add it.
      </p>
      <form
        className="mt-4 space-y-3"
        onSubmit={(event) => {
          event.preventDefault();
          void extract.mutateAsync({
            meetingId,
            text: text.trim() || undefined,
          });
        }}
      >
        <textarea
          className={nativeTextareaClass}
          value={text}
          onChange={(event) => setText(event.target.value)}
          placeholder="Paste extra notes, or leave blank to use the meeting"
        />
        <Button type="submit" disabled={extract.isPending}>
          {extract.isPending ? "Extracting..." : "Extract tasks"}
        </Button>
      </form>
      {extract.error ? (
        <p className="mt-3 text-sm text-destructive">{extract.error.message}</p>
      ) : null}
      {extract.data ? (
        <div className="mt-4 space-y-3">
          <AiSourceNote result={extract.data} />
          <SuggestedTaskList
            tasks={extract.data.tasks}
            projectId={projectId}
            canWrite={canWrite}
          />
        </div>
      ) : null}
    </Surface>
  );
}

