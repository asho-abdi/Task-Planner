/** Badge shown in panel headers when no AI provider is configured. */
function ProviderBadge() {
  const workspaceId = useWorkspaceStore((state) => state.currentWorkspaceId);
  const status = useAiStatus(workspaceId);
  if (!status.data) return null;
  return status.data.enabled ? (
    <Badge variant="primary" dot>
      AI ready
    </Badge>
  ) : (
    <Badge variant="outline" title="No AI provider key is configured; results use templates.">
      Template mode
    </Badge>
  );
}

function AssistantPanel({
  title,
  description,
  action,
  children,
  className,
}: {
  title: string;
  description?: ReactNode;
  action?: ReactNode;
  children?: ReactNode;
  className?: string;
}) {
  return (
    <section
      className={cn(
        "overflow-hidden rounded-xl border border-border bg-card shadow-xs",
        className,
      )}
    >
      <div className="flex flex-wrap items-start justify-between gap-3 border-b border-border bg-primary-soft/40 px-4 py-3 sm:px-5">
        <div className="flex min-w-0 items-start gap-3">
          <span className="flex size-8 shrink-0 items-center justify-center rounded-lg bg-primary-soft text-primary-soft-foreground">
            <Sparkles className="size-4" strokeWidth={2} />
          </span>
          <div className="min-w-0">
            <div className="flex flex-wrap items-center gap-2">
              <h2 className="text-md font-semibold tracking-[-0.01em] text-foreground">
                {title}
              </h2>
              <ProviderBadge />
            </div>
            {description ? (
              <p className="mt-0.5 text-sm text-muted-foreground">{description}</p>
            ) : null}
          </div>
        </div>
        {action ? <div className="shrink-0">{action}</div> : null}
      </div>
      {children ? <div className="space-y-4 p-4 sm:p-5">{children}</div> : null}
    </section>
  );
}

/** Placeholder lines while the assistant is writing. */
function GeneratingLines({ lines = 3 }: { lines?: number }) {
  const widths = ["w-11/12", "w-full", "w-4/5", "w-2/3", "w-3/4"];
  return (
    <div role="status" aria-label="Generating" className="space-y-2.5">
      <div className="flex items-center gap-2 text-xs text-muted-foreground">
        <Sparkles className="size-3.5 animate-pulse text-primary" />
        Generating…
      </div>
      {Array.from({ length: lines }).map((_, index) => (
        <Skeleton key={index} className={cn("h-3", widths[index % widths.length])} />
      ))}
    </div>
  );
}

export function AiSourceNote({ result }: { result: AiEnvelope }) {
  const isAi = result.source === "ai";
  const copy = result.unavailableReason
    ? REASON_COPY[result.unavailableReason]
    : result.source === "heuristic"
      ? "Template result — not AI-generated."
      : "Generated by the AI provider.";
  return (
    <div
      className={cn(
        "flex flex-wrap items-center gap-2 rounded-lg px-3 py-2 text-sm",
        result.unavailableReason
          ? "bg-warning-soft text-warning-soft-foreground"
          : isAi
            ? "bg-primary-soft/60 text-primary-soft-foreground"
            : "bg-muted text-muted-foreground",
      )}
    >
      {result.unavailableReason ? (
        <Info className="size-4 shrink-0" />
      ) : (
        <Badge variant={isAi ? "primary" : "outline"}>
          {isAi ? (
            <>
              <Sparkles /> AI
            </>
          ) : (
            "Template"
          )}
        </Badge>
      )}
      <p>{copy}</p>
    </div>
  );
}

export function SuggestedTaskList({
  tasks,
  projectId,
  canWrite,
}: {
  tasks: SuggestedTask[];
  projectId?: string;
  canWrite?: boolean;
}) {
  const createTask = useCreateTask();
  const [added, setAdded] = useState<string[]>([]);
  const [pendingKey, setPendingKey] = useState<string | null>(null);

  if (tasks.length === 0) {
    return <p className="text-sm text-muted-foreground">No suggested tasks.</p>;
  }

  return (
    <ul className="divide-y divide-border overflow-hidden rounded-lg border border-border">
      {tasks.map((task, index) => {
        const key = `${task.title}-${index}`;
        const already = added.includes(key);
        return (
          <li
            key={key}
            className="flex flex-col gap-3 bg-card px-3 py-3 sm:flex-row sm:items-start sm:justify-between"
          >
            <div className="min-w-0 space-y-1">
              <p className="text-base font-medium text-foreground">{task.title}</p>
              {task.description ? (
                <p className="text-sm text-muted-foreground">{task.description}</p>
              ) : null}
              <div className="flex flex-wrap items-center gap-2 pt-0.5 text-xs text-muted-foreground">
                <PriorityBadge value={task.priority} />
                {task.estimatedHours != null ? (
                  <span className="tabular">{task.estimatedHours}h estimate</span>
                ) : null}
                {task.dueDate ? <span className="tabular">Due {task.dueDate}</span> : null}
              </div>
            </div>
            {canWrite ? (
              <Button
                type="button"
                size="sm"
                variant={already ? "ghost" : "outline"}
                className="shrink-0 self-start"
                disabled={already || createTask.isPending}
                loading={pendingKey === key && createTask.isPending}
                onClick={() => {
                  setPendingKey(key);
                  void createTask
                    .mutateAsync({
                      title: task.title,
                      description: task.description || undefined,
                      priority: task.priority,
                      estimatedHours: task.estimatedHours,
                      dueDate: task.dueDate
                        ? fromDateInputValue(task.dueDate)
                        : undefined,
                      projectId,
                    })
                    .then(() => {
                      setAdded((current) => [...current, key]);
                      toast.success("Task added");
                    })
                    .catch(() => undefined);
                }}
              >
                {already ? (
                  <>
                    <Check /> Added
                  </>
                ) : (
                  <>
                    <Plus /> Add task
                  </>
                )}
              </Button>
            ) : null}
          </li>
        );
      })}
    </ul>
  );
}

export function AiPlanDialog({
  open,
  onOpenChange,
  projectId,
  canWrite,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  projectId?: string;
  canWrite?: boolean;
}) {
  const workspaceId = useWorkspaceStore((state) => state.currentWorkspaceId);
  const status = useAiStatus(open ? workspaceId : null);
  const plan = useGeneratePlan();
  const [prompt, setPrompt] = useState("");

  function handleOpenChange(next: boolean) {
    if (!next) {
      setPrompt("");
      plan.reset();
    }
    onOpenChange(next);
  }

  return (
    <CreateResourceDialog
      open={open}
      onOpenChange={handleOpenChange}
      title="Task plan"
      description={
        status.data?.enabled
          ? "Describe the outcome. The plan loads after you generate it."
          : "AI is optional. Without a provider key you still get a labeled template plan."
      }
    >
      <form
        className="space-y-4"
        onSubmit={(event: FormEvent) => {
          event.preventDefault();
          void plan.mutateAsync({ prompt, projectId });
        }}
      >
        <div className="space-y-2">
          <Label htmlFor="ai-plan-prompt">What needs planning?</Label>
          <textarea
            id="ai-plan-prompt"
            className={nativeTextareaClass}
            value={prompt}
            onChange={(event) => setPrompt(event.target.value)}
            placeholder="Launch the Q3 onboarding flow"
            autoFocus
            required
          />
        </div>
        <div className="flex justify-end">
          <Button
            type="submit"
            disabled={!prompt.trim() || plan.isPending}
            loading={plan.isPending}
          >
            {plan.isPending ? (
              "Generating..."
            ) : (
              <>
                <Sparkles /> Generate plan
              </>
            )}
          </Button>
        </div>
        {plan.isPending ? <GeneratingLines lines={4} /> : null}
        {plan.error ? (
          <ErrorState title="Couldn't generate a plan" description={plan.error.message} />
        ) : null}
        {plan.data ? (
          <div className="space-y-3 animate-fade-in">
            <AiSourceNote result={plan.data} />
            <div>
              <p className="text-md font-semibold text-foreground">{plan.data.title}</p>
              <p className="text-sm text-muted-foreground">{plan.data.summary}</p>
            </div>
            <SuggestedTaskList
              tasks={plan.data.tasks}
              projectId={projectId}
              canWrite={canWrite}
            />
          </div>
        ) : null}
      </form>
    </CreateResourceDialog>
  );
}

export function AiAssistCard({
  taskId,
  projectId,
}: {
  taskId?: string;
  projectId?: string;
}) {
  const assist = useAiAssist();
  const [question, setQuestion] = useState("What should I do next?");

  return (
    <AssistantPanel
      title="AI assistance"
      description="Optional. Core task editing does not wait on this."
    >
      <form
        className="flex flex-col gap-2 sm:flex-row"
        onSubmit={(event) => {
          event.preventDefault();
          void assist.mutateAsync({ question, taskId, projectId });
        }}
      >
        <Input
          value={question}
          onChange={(event) => setQuestion(event.target.value)}
          placeholder="Ask for the next action"
          aria-label="Question for the assistant"
          className="flex-1"
        />
        <Button
          type="submit"
          disabled={!question.trim() || assist.isPending}
          loading={assist.isPending}
        >
          {assist.isPending ? "Asking..." : "Ask"}
        </Button>
      </form>
      {assist.isPending ? <GeneratingLines /> : null}
      {assist.error ? (
        <ErrorState title="The assistant couldn't answer" description={assist.error.message} />
      ) : null}
      {assist.data ? (
        <div className="space-y-3 animate-fade-in">
          <AiSourceNote result={assist.data} />
          <p className="text-base text-foreground">{assist.data.answer}</p>
          {assist.data.suggestions.length > 0 ? (
            <ul className="list-disc space-y-1 pl-5 text-sm text-muted-foreground marker:text-primary">
              {assist.data.suggestions.map((item) => (
                <li key={item}>{item}</li>
              ))}
            </ul>
          ) : null}
        </div>
      ) : null}
    </AssistantPanel>
  );
}

export function AiExtractCard({
  meetingId,
  projectId,
  defaultText,
  canWrite,
}: {
  meetingId?: string;
  projectId?: string;
  defaultText?: string;
  canWrite?: boolean;
}) {
  const extract = useExtractTasks();
  const [text, setText] = useState(defaultText ?? "");

  return (
    <AssistantPanel
      title="Extract tasks"
      description="Pull suggested tasks from notes. Nothing is created until you add it."
    >
      <form
        className="space-y-3"
        onSubmit={(event) => {
          event.preventDefault();
          void extract.mutateAsync({
            meetingId,
            text: text.trim() || undefined,
          });
        }}
      >
        <textarea
          className={nativeTextareaClass}
          value={text}
          onChange={(event) => setText(event.target.value)}
          placeholder="Paste extra notes, or leave blank to use the meeting"
          aria-label="Notes to extract tasks from"
        />
        <Button
          type="submit"
          variant="soft"
          disabled={extract.isPending}
          loading={extract.isPending}
        >
          {extract.isPending ? (
            "Extracting..."
          ) : (
            <>
              <Sparkles /> Extract tasks
            </>
          )}
        </Button>
      </form>
      {extract.isPending ? <GeneratingLines lines={4} /> : null}
      {extract.error ? (
        <ErrorState title="Couldn't extract tasks" description={extract.error.message} />
      ) : null}
      {extract.data ? (
        <div className="space-y-3 animate-fade-in">
          <AiSourceNote result={extract.data} />
          <SuggestedTaskList
            tasks={extract.data.tasks}
            projectId={projectId}
            canWrite={canWrite}
          />
        </div>
      ) : null}
    </AssistantPanel>
  );
}

export function AiNarrativeCard({ from, to }: { from: string; to: string }) {
  const narrative = useReportNarrative();
  const hasBody = narrative.isPending || Boolean(narrative.error) || Boolean(narrative.data);

  return (
    <AssistantPanel
      title="Narrative"
      description="Generated on demand from this report. Not loaded automatically."
      action={
        <Button
          type="button"
          variant="soft"
          size="sm"
          disabled={narrative.isPending}
          loading={narrative.isPending}
          onClick={() => void narrative.mutateAsync({ from, to })}
        >
          {narrative.isPending ? (
            "Writing..."
          ) : (
            <>
              <Sparkles /> {narrative.data ? "Rewrite" : "Write narrative"}
            </>
          )}
        </Button>
      }
    >
      {hasBody ? (
        <>
          {narrative.isPending ? <GeneratingLines lines={4} /> : null}
          {narrative.error ? (
            <ErrorState
              title="Couldn't write the narrative"
              description={narrative.error.message}
            />
          ) : null}
          {narrative.data && !narrative.isPending ? (
            <div className="space-y-3 animate-fade-in">
              <AiSourceNote result={narrative.data} />
              <p className="text-md font-semibold text-foreground">
                {narrative.data.headline}
              </p>
              <p className="text-base leading-relaxed text-muted-foreground">
                {narrative.data.narrative}
              </p>
              {narrative.data.highlights.length > 0 ? (
                <ul className="space-y-1.5 text-sm text-foreground">
                  {narrative.data.highlights.map((item) => (
                    <li key={item} className="flex gap-2">
                      <span
                        aria-hidden
                        className="mt-1.5 size-1.5 shrink-0 rounded-full bg-primary"
                      />
                      {item}
                    </li>
                  ))}
                </ul>
              ) : null}
            </div>
          ) : null}
        </>
      ) : null}
    </AssistantPanel>
  );
}
